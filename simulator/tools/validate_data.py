def load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def safe_slug(value: Any, fallback: str = "incident") -> str:
    slug = re.sub(r"[^a-zA-Z0-9_\-]+", "_", str(value or "")).strip("_")
    return slug or fallback


def candidate_default_root() -> Path:
    for path in DEFAULT_ROOT_CANDIDATES:
        if path.exists():
            return path
    return DEFAULT_ROOT_CANDIDATES[0]


# Validator-only conveniences for selecting old and new incident naming variants.
# This does not change simulator incident labels; it only helps filtering reports.
INCIDENT_FILTER_ALIASES = {
    "terrorist incident": ["terrorist incident", "terrorist attack"],
    "terrorist attack": ["terrorist attack", "terrorist incident"],
}


def normalize_filter_text(value: Any) -> str:
    """Normalize text for robust incident-type filtering."""
    return re.sub(r"[^a-z0-9]+", "_", str(value or "").lower()).strip("_")


def split_incident_type_filters(values: Optional[Iterable[str]]) -> List[str]:
    """Parse repeated or comma-separated incident-type filters."""
    if not values:
        return []
    out: List[str] = []
    for value in values:
        for part in str(value).split(","):
            part = part.strip()
            if part:
                out.append(part)
    return out


def expanded_incident_type_filters(values: Optional[Iterable[str]]) -> List[str]:
    """Expand user incident-type filters with validator-only aliases."""
    raw = split_incident_type_filters(values)
    expanded: List[str] = []
    seen = set()
    for value in raw:
        candidates = [value] + INCIDENT_FILTER_ALIASES.get(value.lower().strip(), [])
        for candidate in candidates:
            norm = normalize_filter_text(candidate)
            if norm and norm not in seen:
                expanded.append(candidate)
                seen.add(norm)
    return expanded


def text_matches_incident_filter(text: Any, filter_values: Sequence[str]) -> bool:
    """Return True if text appears to match any requested incident type."""
    if not filter_values:
        return True
    candidate = normalize_filter_text(text)
    if not candidate:
        return False
    for filter_value in filter_values:
        query = normalize_filter_text(filter_value)
        if not query:
            continue
        # Exact and substring matching makes folders like wildfire9 match wildfire,
        # while still allowing multi-word labels such as large_civil_protest.
        if query == candidate or query in candidate or candidate in query:
            return True
    return False


def run_matches_incident_filter(run: "RunSummary", filter_values: Sequence[str]) -> bool:
    """Keep a run if its folder/run id or any sub-incident type matches.

    The whole run is retained once matched, rather than dropping non-matching
    sub-incidents. This preserves the high-level question: whether all
    sub-incidents in the selected incident run pass the area check.
    """
    if not filter_values:
        return True

    run_dir_name = Path(run.run_dir).name
    if text_matches_incident_filter(run.run_id, filter_values):
        return True
    if text_matches_incident_filter(run_dir_name, filter_values):
        return True

    return any(text_matches_incident_filter(sub.incident_type, filter_values) for sub in run.subincidents)


def filter_runs_by_incident_types(
    runs: List["RunSummary"],
    incident_types: Optional[Iterable[str]],
) -> List["RunSummary"]:
    """Restrict validation output to selected incident types, if provided."""
    filters = expanded_incident_type_filters(incident_types)
    if not filters:
        return runs
    return [run for run in runs if run_matches_incident_filter(run, filters)]


def is_gt_file(path: Path) -> bool:
    name = path.name.lower()
    if not name.endswith(".json"):
        return False
    if "plan" in name or "summary" in name or "schedule" in name:
        return False
    return "_gt_" in name or name.startswith("gt_") or "gt_step" in name or name.endswith("_gt.json")


def discover_run_dirs(root: Path) -> List[Path]:
    """Return directories that contain at least one GT JSON file."""
    dirs = {p.parent for p in root.rglob("*.json") if is_gt_file(p)}
    return sorted(dirs)


def find_plan_candidates(run_dir: Path, root: Path) -> List[Path]:
    """Find plausible plan JSON files in the run directory or its ancestors."""
    candidates: List[Path] = []
    current = run_dir
    root = root.resolve()
    while True:
        candidates.extend(sorted(current.glob("*_plan.json")))
        plan = current / "plan.json"
        if plan.exists():
            candidates.append(plan)
        if current.resolve() == root or current.parent == current:
            break
        current = current.parent
    # Deduplicate while preserving order.
    seen = set()
    out = []
    for path in candidates:
        if path not in seen:
            out.append(path)
            seen.add(path)
    return out


def choose_plan_file(run_dir: Path, root: Path, gt_files: Sequence[Path]) -> Tuple[Optional[Path], Optional[Dict[str, Any]]]:
    """Choose the plan file that best matches GT incident ids."""
    gt_ids = []
    for path in gt_files[:20]:
        try:
            data = load_json(path)
        except Exception:
            continue
        if isinstance(data, dict) and data.get("incident_id"):
            gt_ids.append(str(data["incident_id"]))

    best_path = None
    best_data = None
    best_score = -1
    for path in find_plan_candidates(run_dir, root):
        try:
            data = load_json(path)
        except Exception:
            continue
        if not isinstance(data, dict):
            continue
        run_id = str(data.get("run_id") or "")
        sub_ids = []
        if isinstance(data.get("plan"), list):
            for item in data["plan"]:
                if isinstance(item, dict) and item.get("sub_incident_id"):
                    sub_ids.append(str(item["sub_incident_id"]))

        score = 0
        if run_id and any(gt_id.startswith(run_id) for gt_id in gt_ids):
            score += 100
        score += sum(1 for sub_id in sub_ids if any(sub_id in gt_id for gt_id in gt_ids))
        if path.parent == run_dir:
            score += 10

        if score > best_score:
            best_path = path
            best_data = data
            best_score = score

    return best_path, best_data


def parse_step_from_gt(gt_data: Dict[str, Any], path: Path) -> Optional[Any]:
    if gt_data.get("step") is not None:
        return gt_data.get("step")
    match = re.search(r"(?:_gt_|gt_step|step)(\d+)", path.stem)
    if match:
        return int(match.group(1))
    return None


def expected_subincidents_from_plan(plan_data: Optional[Dict[str, Any]]) -> Dict[str, Dict[str, Any]]:
    if not isinstance(plan_data, dict) or not isinstance(plan_data.get("plan"), list):
        return {}
    out: Dict[str, Dict[str, Any]] = {}
    for idx, item in enumerate(plan_data["plan"]):
        if not isinstance(item, dict):
            continue
        sub_id = str(item.get("sub_incident_id") or f"incident_{idx}")
        out[sub_id] = item
    return out


def infer_subincident_id(
    incident_id: str,
    plan_data: Optional[Dict[str, Any]],
    expected_subs: Dict[str, Dict[str, Any]],
) -> str:
    if expected_subs:
        # Longest first protects ids like incident_1 vs incident_10.
        for sub_id in sorted(expected_subs.keys(), key=len, reverse=True):
            if sub_id and sub_id in incident_id:
                return sub_id

    run_id = str(plan_data.get("run_id") if isinstance(plan_data, dict) else "" or "")
    if run_id and incident_id.startswith(run_id + "_"):
        return incident_id[len(run_id) + 1 :]

    return incident_id or "unknown_subincident"


def infer_incident_type(
    sub_id: str,
    gt_data: Dict[str, Any],
    plan_data: Optional[Dict[str, Any]],
    expected_subs: Dict[str, Dict[str, Any]],
    run_dir: Path,
) -> str:
    if sub_id in expected_subs:
        return str(expected_subs[sub_id].get("incident_type") or "unknown")
    if gt_data.get("incident_type"):
        return str(gt_data["incident_type"])
    if isinstance(plan_data, dict) and plan_data.get("incident_type"):
        return str(plan_data["incident_type"])
    return run_dir.name.rstrip("0123456789_") or "unknown"


def gt_region_results(
    gt_data: Dict[str, Any],
    legacy_multi_location_mode: str = "composite",
) -> List[RegionAreaResult]:
    """Extract and area-check all regions represented in one GT JSON object.

    New GT files should contain a single ``incident_region``. For legacy GT
    files that have multiple ``locations`` but no ``incident_region``, the
    default ``composite`` mode treats the locations as one enclosing footprint.
    Use ``separate`` to reproduce the older stricter behavior.
    """
    incident_region = gt_data.get("incident_region")
    if isinstance(incident_region, dict):
        name = str(incident_region.get("name") or "incident_region")
        result = region_record_area(name, incident_region)
        result.location_count_in_gt = 1
        return [result]

    locations = gt_data.get("locations")
    location_items: List[Tuple[str, Any]] = []

    if isinstance(locations, dict):
        location_items = [(str(location_name), record) for location_name, record in locations.items()]
    elif isinstance(locations, list):
        for idx, record in enumerate(locations):
            if isinstance(record, dict):
                name = str(
                    record.get("location_name")
                    or record.get("name")
                    or record.get("query")
                    or f"location_{idx}"
                )
            else:
                name = f"location_{idx}"
            location_items.append((name, record))

    if len(location_items) > 1 and legacy_multi_location_mode == "composite":
        return [composite_region_area_from_location_records(location_items)]

    results: List[RegionAreaResult] = []
    for location_name, record in location_items:
        result = region_record_area(location_name, record)
        results.append(result)

    count = len(results)
    for result in results:
        result.location_count_in_gt = count
    return results


