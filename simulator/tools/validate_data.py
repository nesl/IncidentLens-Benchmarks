def _mean(values: Sequence[float], default: float = 0.0) -> float:
    return sum(values) / len(values) if values else default


def _lonlat_ring_area_km2(ring: Sequence[LonLat]) -> float:
    """Approximate a lon/lat ring area by local equirectangular projection.

    This avoids requiring Shapely/pyproj. It is accurate enough for the
    kilometer-scale Los Angeles regions generated by the simulator.
    """
    if len(ring) < 3:
        return 0.0

    lons = [p[0] for p in ring]
    lats = [p[1] for p in ring]
    lon0 = _mean(lons)
    lat0 = _mean(lats)
    cos_lat0 = math.cos(math.radians(lat0))

    points_xy = []
    for lon, lat in ring:
        x = (lon - lon0) * 111.320 * cos_lat0
        y = (lat - lat0) * 110.574
        points_xy.append((x, y))

    area2 = 0.0
    for (x1, y1), (x2, y2) in zip(points_xy, points_xy[1:] + points_xy[:1]):
        area2 += x1 * y2 - x2 * y1
    return abs(area2) / 2.0


def _polygon_coordinates_area_km2(coordinates: Any) -> Optional[float]:
    """Area for GeoJSON Polygon coordinates: [outer, hole1, ...]."""
    if not isinstance(coordinates, list) or not coordinates:
        return None

    rings: List[List[LonLat]] = []
    for ring in coordinates:
        if not isinstance(ring, list) or len(ring) < 3:
            continue
        parsed_ring: List[LonLat] = []
        for point in ring:
            if not isinstance(point, (list, tuple)) or len(point) < 2:
                continue
            try:
                lon = float(point[0])
                lat = float(point[1])
            except (TypeError, ValueError):
                continue
            parsed_ring.append((lon, lat))
        if len(parsed_ring) >= 3:
            rings.append(parsed_ring)

    if not rings:
        return None

    outer_area = _lonlat_ring_area_km2(rings[0])
    hole_area = sum(_lonlat_ring_area_km2(ring) for ring in rings[1:])
    return max(0.0, outer_area - hole_area)


def geojson_area_km2(geometry: Any) -> Optional[float]:
    """Approximate area for GeoJSON Polygon/MultiPolygon/GeometryCollection."""
    if not isinstance(geometry, dict):
        return None

    gtype = str(geometry.get("type") or "").strip()
    coords = geometry.get("coordinates")

    if gtype == "Polygon":
        return _polygon_coordinates_area_km2(coords)

    if gtype == "MultiPolygon":
        if not isinstance(coords, list):
            return None
        areas = [_polygon_coordinates_area_km2(poly_coords) for poly_coords in coords]
        areas = [a for a in areas if a is not None]
        return sum(areas) if areas else None

    if gtype == "GeometryCollection":
        geometries = geometry.get("geometries")
        if not isinstance(geometries, list):
            return None
        areas = [geojson_area_km2(g) for g in geometries]
        areas = [a for a in areas if a is not None]
        return sum(areas) if areas else None

    return None


_VERTEX_RE = re.compile(
    r"Sample boundary vertices as \(latitude, longitude\):\s*(\[[^\]]*\])",
    flags=re.IGNORECASE | re.DOTALL,
)
_BBOX_RE = re.compile(
    r"south\s*=\s*([-+]?\d+(?:\.\d+)?).*?"
    r"west\s*=\s*([-+]?\d+(?:\.\d+)?).*?"
    r"north\s*=\s*([-+]?\d+(?:\.\d+)?).*?"
    r"east\s*=\s*([-+]?\d+(?:\.\d+)?)",
    flags=re.IGNORECASE | re.DOTALL,
)


def _area_from_summary_vertices(region_summary: str) -> Optional[float]:
    match = _VERTEX_RE.search(region_summary or "")
    if not match:
        return None
    try:
        latlon_values = ast.literal_eval(match.group(1))
    except (SyntaxError, ValueError):
        return None

    ring: List[LonLat] = []
    for item in latlon_values:
        if not isinstance(item, (list, tuple)) or len(item) < 2:
            continue
        try:
            lat = float(item[0])
            lon = float(item[1])
        except (TypeError, ValueError):
            continue
        ring.append((lon, lat))

    if len(ring) < 3:
        return None
    return _lonlat_ring_area_km2(ring)


def _area_from_summary_bbox(region_summary: str) -> Optional[float]:
    match = _BBOX_RE.search(region_summary or "")
    if not match:
        return None
    try:
        south, west, north, east = map(float, match.groups())
    except (TypeError, ValueError):
        return None

    ring = [(west, south), (east, south), (east, north), (west, north), (west, south)]
    return _lonlat_ring_area_km2(ring)


def _bbox_area_km2(south: float, west: float, north: float, east: float) -> float:
    ring = [(west, south), (east, south), (east, north), (west, north), (west, south)]
    return _lonlat_ring_area_km2(ring)


def _geojson_bbox_latlon(geometry: Any) -> Optional[Tuple[float, float, float, float]]:
    """Return (south, west, north, east) for GeoJSON coordinates."""
    if not isinstance(geometry, dict):
        return None

    coords = geometry.get("coordinates")
    points: List[Tuple[float, float]] = []

    def walk(value: Any) -> None:
        if isinstance(value, (list, tuple)) and len(value) >= 2:
            if all(not isinstance(x, (list, tuple)) for x in value[:2]):
                try:
                    lon = float(value[0])
                    lat = float(value[1])
                except (TypeError, ValueError):
                    return
                points.append((lat, lon))
                return
        if isinstance(value, (list, tuple)):
            for child in value:
                walk(child)

    walk(coords)
    if not points:
        return None
    lats = [p[0] for p in points]
    lons = [p[1] for p in points]
    return min(lats), min(lons), max(lats), max(lons)


def _summary_bbox_latlon(region_summary: str) -> Optional[Tuple[float, float, float, float]]:
    match = _BBOX_RE.search(region_summary or "")
    if not match:
        return None
    try:
        south, west, north, east = map(float, match.groups())
    except (TypeError, ValueError):
        return None
    return south, west, north, east


def region_record_bbox_latlon(record: Any) -> Optional[Tuple[float, float, float, float]]:
    """Best-effort bbox for a GT location/incident-region record."""
    if not isinstance(record, dict):
        return None

    bbox = _geojson_bbox_latlon(record.get("geometry_geojson"))
    if bbox is not None:
        return bbox

    summary_bbox = _summary_bbox_latlon(str(record.get("region_summary") or ""))
    if summary_bbox is not None:
        return summary_bbox

    # Last resort for partially serialized records: use representative point only.
    lat = record.get("representative_latitude", record.get("latitude"))
    lon = record.get("representative_longitude", record.get("longitude"))
    try:
        if lat is not None and lon is not None:
            lat_f = float(lat)
            lon_f = float(lon)
            return lat_f, lon_f, lat_f, lon_f
    except (TypeError, ValueError):
        pass

    return None


def composite_region_area_from_location_records(locations: Sequence[Tuple[str, Any]]) -> RegionAreaResult:
    """Treat legacy multi-location GT files as one enclosing incident footprint."""
    bboxes = [region_record_bbox_latlon(record) for _, record in locations]
    bboxes = [bbox for bbox in bboxes if bbox is not None]
    location_count = len(locations)

    if not bboxes:
        return RegionAreaResult(
            name="legacy_composite_region",
            area_km2=None,
            source="legacy_composite_bbox",
            status="unknown",
            message="legacy GT had multiple locations but no parseable bboxes",
            location_count_in_gt=location_count,
        )

    south = min(bbox[0] for bbox in bboxes)
    west = min(bbox[1] for bbox in bboxes)
    north = max(bbox[2] for bbox in bboxes)
    east = max(bbox[3] for bbox in bboxes)
    return RegionAreaResult(
        name="legacy_composite_region",
        area_km2=_bbox_area_km2(south, west, north, east),
        source="legacy_composite_bbox",
        status="computed",
        message=(
            f"legacy GT with {location_count} locations; area estimated as enclosing bbox "
            f"south={south:.6f}, west={west:.6f}, north={north:.6f}, east={east:.6f}"
        ),
        location_count_in_gt=location_count,
    )


def region_record_area(location_name: str, record: Any) -> RegionAreaResult:
    """Compute area for one location/incident-region record."""
    if not isinstance(record, dict):
        return RegionAreaResult(
            name=location_name,
            area_km2=None,
            source="invalid_record",
            status="unknown",
            message=f"region record is {type(record).__name__}, not dict",
        )

    geometry = record.get("geometry_geojson")
    area = geojson_area_km2(geometry)
    if area is not None:
        return RegionAreaResult(
            name=location_name,
            area_km2=area,
            source="geometry_geojson",
            status="computed",
        )

    # Prefer the simulator-computed dimensions if geometry is absent. This gives
    # a conservative rectangle estimate for old/partially serialized data.
    size_check = record.get("region_size_check")
    if isinstance(size_check, dict):
        width = size_check.get("final_bbox_width_km")
        height = size_check.get("final_bbox_height_km")
        try:
            if width is not None and height is not None:
                return RegionAreaResult(
                    name=location_name,
                    area_km2=float(width) * float(height),
                    source="region_size_check_final_bbox",
                    status="computed",
                    message="area estimated as final_bbox_width_km * final_bbox_height_km",
                )
        except (TypeError, ValueError):
            pass

    summary = str(record.get("region_summary") or "")
    area = _area_from_summary_vertices(summary)
    if area is not None:
        return RegionAreaResult(
            name=location_name,
            area_km2=area,
            source="region_summary_vertices",
            status="computed",
        )

    area = _area_from_summary_bbox(summary)
    if area is not None:
        return RegionAreaResult(
            name=location_name,
            area_km2=area,
            source="region_summary_bbox",
            status="computed",
            message="fallback rectangle from bounding box",
        )

    return RegionAreaResult(
        name=location_name,
        area_km2=None,
        source="missing_geometry",
        status="unknown",
        message="no geometry_geojson, region_size_check dimensions, parseable vertices, or parseable bbox",
    )


