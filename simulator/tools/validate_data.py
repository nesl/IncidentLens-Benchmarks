def validate_gt_file(
    path: Path,
    plan_data: Optional[Dict[str, Any]],
    expected_subs: Dict[str, Dict[str, Any]],
    run_dir: Path,
    legacy_multi_location_mode: str = "composite",
) -> GroundTruthStepResult:
    data = load_json(path)
    if not isinstance(data, dict):
        raise ValueError(f"GT file is not a JSON object: {path}")

    incident_id = str(data.get("incident_id") or path.stem)
    sub_id = infer_subincident_id(incident_id, plan_data, expected_subs)
    incident_type = infer_incident_type(sub_id, data, plan_data, expected_subs, run_dir)
    step = parse_step_from_gt(data, path)
    results = gt_region_results(data, legacy_multi_location_mode=legacy_multi_location_mode)

    if not results:
        results = [
            RegionAreaResult(
                name="missing_region",
                area_km2=None,
                source="missing_region",
                status="unknown",
                message="GT file has neither incident_region nor locations",
            )
        ]

    return GroundTruthStepResult(
        gt_path=str(path),
        incident_id=incident_id,
        step=step,
        sub_incident_id=sub_id,
        incident_type=incident_type,
        region_results=results,
    )


def summarize_run(
    run_dir: Path,
    root: Path,
    min_area_km2: float,
    tolerance_km2: float,
    legacy_multi_location_mode: str = "composite",
) -> RunSummary:
    gt_files = sorted(p for p in run_dir.glob("*.json") if is_gt_file(p))
    plan_path, plan_data = choose_plan_file(run_dir, root, gt_files)
    expected_subs = expected_subincidents_from_plan(plan_data)

    if isinstance(plan_data, dict):
        run_id = str(plan_data.get("run_id") or run_dir.name)
        high_level = bool(plan_data.get("high_level", bool(expected_subs)))
    else:
        run_id = run_dir.name
        high_level = False

    step_results: List[GroundTruthStepResult] = []
    for path in gt_files:
        try:
            step_results.append(
                validate_gt_file(
                    path,
                    plan_data,
                    expected_subs,
                    run_dir,
                    legacy_multi_location_mode=legacy_multi_location_mode,
                )
            )
        except Exception as exc:
            # Treat unreadable/malformed files as an unknown-area synthetic step.
            step_results.append(
                GroundTruthStepResult(
                    gt_path=str(path),
                    incident_id=path.stem,
                    step=None,
                    sub_incident_id=path.stem,
                    incident_type="unknown",
                    region_results=[
                        RegionAreaResult(
                            name="unreadable_gt",
                            area_km2=None,
                            source="exception",
                            status="unknown",
                            message=repr(exc),
                        )
                    ],
                )
            )

    by_sub: Dict[str, List[GroundTruthStepResult]] = defaultdict(list)
    for result in step_results:
        by_sub[result.sub_incident_id].append(result)

    # Include plan-expected subincidents even if no GT file was found.
    for sub_id in expected_subs:
        by_sub.setdefault(sub_id, [])

    sub_summaries: List[SubIncidentSummary] = []
    for sub_id in sorted(by_sub.keys()):
        results = by_sub[sub_id]
        expected = sub_id in expected_subs
        incident_type = (
            str(expected_subs[sub_id].get("incident_type"))
            if expected
            else (results[0].incident_type if results else "unknown")
        )
        known_areas = [
            region.area_km2
            for step_result in results
            for region in step_result.region_results
            if region.area_km2 is not None
        ]
        failing_files = [
            step_result.gt_path
            for step_result in results
            if not step_result.ok(min_area_km2, tolerance_km2)
        ]
        unknown = any(
            region.area_km2 is None
            for step_result in results
            for region in step_result.region_results
        )
        multiple = any(step_result.has_multiple_regions for step_result in results)
        gt_steps = [step_result.step for step_result in results if step_result.step is not None]
        all_ok = bool(results) and not failing_files
        notes: List[str] = []
        if not results:
            notes.append("expected in plan but no GT files were found")
        if multiple:
            notes.append("one or more GT files contains multiple locations/regions")
        if unknown:
            notes.append("one or more GT regions had unknown area")

        sub_summaries.append(
            SubIncidentSummary(
                run_dir=str(run_dir),
                run_id=run_id,
                sub_incident_id=sub_id,
                incident_type=incident_type,
                gt_count=len(results),
                expected_from_plan=expected,
                gt_steps=gt_steps,
                min_area_km2=min(known_areas) if known_areas else None,
                max_area_km2=max(known_areas) if known_areas else None,
                all_steps_ok=all_ok,
                has_unknown_area=unknown,
                has_multiple_regions_in_any_gt=multiple,
                failing_gt_files=failing_files,
                notes=notes,
            )
        )

    expected_count = len(expected_subs) if expected_subs else len(sub_summaries)
    found_expected = sum(1 for s in sub_summaries if (not expected_subs or s.expected_from_plan) and s.gt_count > 0)
    all_expected_found = found_expected == expected_count
    passing = sum(1 for s in sub_summaries if s.all_steps_ok)
    run_known_areas = [s.min_area_km2 for s in sub_summaries if s.min_area_km2 is not None]
    all_ok = bool(sub_summaries) and all_expected_found and all(s.all_steps_ok for s in sub_summaries)

    return RunSummary(
        run_dir=str(run_dir),
        run_id=run_id,
        high_level=high_level,
        plan_path=str(plan_path) if plan_path else None,
        gt_file_count=len(gt_files),
        expected_subincident_count=expected_count,
        found_subincident_count=len([s for s in sub_summaries if s.gt_count > 0]),
        passing_subincident_count=passing,
        all_expected_subincidents_found=all_expected_found,
        all_subincidents_ok=all_ok,
        min_area_km2=min(run_known_areas) if run_known_areas else None,
        subincidents=sub_summaries,
    )


def validate_root(
    root: Path,
    min_area_km2: float,
    tolerance_km2: float,
    incident_types: Optional[Iterable[str]] = None,
    legacy_multi_location_mode: str = "composite",
) -> List[RunSummary]:
    run_dirs = discover_run_dirs(root)
    runs = [
        summarize_run(
            run_dir,
            root,
            min_area_km2,
            tolerance_km2,
            legacy_multi_location_mode=legacy_multi_location_mode,
        )
        for run_dir in run_dirs
    ]
    return filter_runs_by_incident_types(runs, incident_types)


