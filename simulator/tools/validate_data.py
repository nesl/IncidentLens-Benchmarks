#!/usr/bin/env python3
"""Validate simulator ground-truth incident-region areas.

This script scans simulator batch outputs under ``generated/batch_incident_runs``
(or a user-provided root), reads plan and ``*_gt_*.json`` files, estimates each
incident/sub-incident region area in km^2, and reports whether every
sub-incident is simulated over a sufficiently large region.

It supports both ground-truth formats used by the simulator:

1. New format:
   ``gt["incident_region"]["geometry_geojson"]`` contains the exact simulated
   polygon serialized by the simulator.
2. Older format:
   ``gt["locations"]`` contains one or more location records whose
   ``region_summary`` text includes bounding boxes and sampled boundary
   vertices. The validator parses those summaries as a fallback.

Default pass criterion: every region representation for every step of a
sub-incident must be at least 4.0 km^2, with a small numeric tolerance.
"""

from __future__ import annotations

import argparse
import ast
import csv
import json
import math
import re
import sys
