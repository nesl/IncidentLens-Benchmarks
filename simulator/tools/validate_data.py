def fmt_area(area: Optional[float]) -> str:
    return "unknown" if area is None else f"{area:.3f}"


def print_table(rows: List[List[Any]], headers: List[str]) -> None:
    if not rows:
        print("(none)")
        return
    values = [[str(x) for x in row] for row in rows]
    widths = [len(h) for h in headers]
    for row in values:
        for i, value in enumerate(row):
            widths[i] = max(widths[i], len(value))

    def line(parts: Sequence[str]) -> str:
        return "  ".join(part.ljust(widths[i]) for i, part in enumerate(parts))

    print(line(headers))
    print(line(["-" * w for w in widths]))
    for row in values:
        print(line(row))


def print_human_summary(runs: List[RunSummary], min_area_km2: float, tolerance_km2: float) -> None:
    total_runs = len(runs)
    passing_runs = sum(1 for r in runs if r.all_subincidents_ok)
    total_subs = sum(len(r.subincidents) for r in runs)
    passing_subs = sum(s.all_steps_ok for r in runs for s in r.subincidents)
    high_level_runs = [r for r in runs if r.high_level]
    passing_high_level = sum(1 for r in high_level_runs if r.all_subincidents_ok)

    print("\n=== Aggregate validation summary ===")
    print(f"Area threshold: {min_area_km2:.3f} km^2; tolerance: {tolerance_km2:.3f} km^2")
    print(f"Runs checked: {total_runs}")
    print(f"Runs with all subincidents passing: {passing_runs}/{total_runs}")
    print(f"High-level runs with all subincidents passing: {passing_high_level}/{len(high_level_runs)}")
    print(f"Subincidents passing: {passing_subs}/{total_subs}")

    print("\n=== Run-level summary ===")
    print_table(
        [
            [
                Path(r.run_dir).name,
                "yes" if r.high_level else "no",
                f"{r.passing_subincident_count}/{len(r.subincidents)}",
                "yes" if r.all_expected_subincidents_found else "no",
                "PASS" if r.all_subincidents_ok else "FAIL",
                fmt_area(r.min_area_km2),
            ]
            for r in runs
        ],
        ["run_dir", "high_level", "sub_ok", "expected_found", "status", "min_area_km2"],
    )

    failing_subs = [s for r in runs for s in r.subincidents if not s.all_steps_ok]
    print("\n=== Failing / unknown subincidents ===")
    print_table(
        [
            [
                Path(s.run_dir).name,
                s.sub_incident_id,
                s.incident_type,
                s.gt_count,
                fmt_area(s.min_area_km2),
                "; ".join(s.notes) if s.notes else "; ".join(Path(p).name for p in s.failing_gt_files[:3]),
            ]
            for s in failing_subs
        ],
        ["run_dir", "subincident", "type", "gt_files", "min_area_km2", "notes/failing_files"],
    )

    print("\n=== High-level incidents whose all subincidents pass ===")
    print_table(
        [
            [Path(r.run_dir).name, r.run_id, len(r.subincidents), fmt_area(r.min_area_km2)]
            for r in high_level_runs
            if r.all_subincidents_ok
        ],
        ["run_dir", "run_id", "subincident_count", "min_area_km2"],
    )


def flatten_subincident_rows(runs: List[RunSummary]) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    for run in runs:
        for sub in run.subincidents:
            rows.append(
                {
                    "run_dir": run.run_dir,
                    "run_id": run.run_id,
                    "high_level": run.high_level,
                    "sub_incident_id": sub.sub_incident_id,
                    "incident_type": sub.incident_type,
                    "gt_count": sub.gt_count,
                    "expected_from_plan": sub.expected_from_plan,
                    "min_area_km2": sub.min_area_km2,
                    "max_area_km2": sub.max_area_km2,
                    "all_steps_ok": sub.all_steps_ok,
                    "has_unknown_area": sub.has_unknown_area,
                    "has_multiple_regions_in_any_gt": sub.has_multiple_regions_in_any_gt,
                    "failing_gt_files": ";".join(sub.failing_gt_files),
                    "notes": "; ".join(sub.notes),
                }
            )
    return rows


def write_json(
    path: Path,
    runs: List[RunSummary],
    min_area_km2: float,
    tolerance_km2: float,
    incident_types: Optional[Iterable[str]] = None,
    legacy_multi_location_mode: str = "composite",
) -> None:
    payload = {
        "min_area_km2": min_area_km2,
        "tolerance_km2": tolerance_km2,
        "incident_type_filter": split_incident_type_filters(incident_types),
        "legacy_multi_location_mode": legacy_multi_location_mode,
        "runs": [asdict(r) for r in runs],
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2)


def write_csv(path: Path, runs: List[RunSummary]) -> None:
    rows = flatten_subincident_rows(runs)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


