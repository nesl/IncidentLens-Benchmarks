from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Dict, Iterable, Iterator, List, Optional, Sequence, Tuple

DEFAULT_ROOT_CANDIDATES = [
    Path("generated/batch_incident_runs"),
    Path("simulator/generated/batch_small_area"),
]
DEFAULT_MIN_AREA_KM2 = 2.0
DEFAULT_TOLERANCE_KM2 = 0.05

LatLon = Tuple[float, float]
LonLat = Tuple[float, float]


@dataclass
class RegionAreaResult:
    """One region-area estimate from a GT file."""

    name: str
    area_km2: Optional[float]
    source: str
    status: str
    message: str = ""
    location_count_in_gt: int = 1

    @property
    def known(self) -> bool:
        return self.area_km2 is not None


@dataclass
class GroundTruthStepResult:
    """Validation result for one GT JSON file / simulator step."""

    gt_path: str
    incident_id: str
    step: Optional[Any]
    sub_incident_id: str
    incident_type: str
    region_results: List[RegionAreaResult]

    @property
    def min_area_km2(self) -> Optional[float]:
        known = [r.area_km2 for r in self.region_results if r.area_km2 is not None]
        return min(known) if known else None

    @property
    def has_multiple_regions(self) -> bool:
        return len(self.region_results) > 1

    def ok(self, min_area_km2: float, tolerance_km2: float) -> bool:
        if not self.region_results:
            return False
        for result in self.region_results:
            if result.area_km2 is None:
                return False
            if result.area_km2 + tolerance_km2 < min_area_km2:
                return False
        return True


@dataclass
class SubIncidentSummary:
    run_dir: str
    run_id: str
    sub_incident_id: str
    incident_type: str
    gt_count: int = 0
    expected_from_plan: bool = False
    gt_steps: List[Any] = field(default_factory=list)
    min_area_km2: Optional[float] = None
    max_area_km2: Optional[float] = None
    all_steps_ok: bool = False
    has_unknown_area: bool = False
    has_multiple_regions_in_any_gt: bool = False
    failing_gt_files: List[str] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)


@dataclass
class RunSummary:
    run_dir: str
    run_id: str
    high_level: bool
    plan_path: Optional[str]
    gt_file_count: int
    expected_subincident_count: int
    found_subincident_count: int
    passing_subincident_count: int
    all_expected_subincidents_found: bool
    all_subincidents_ok: bool
    min_area_km2: Optional[float]
    subincidents: List[SubIncidentSummary]


