def parse_args(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Validate simulator ground-truth incident regions under generated/batch_incident_runs.",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=candidate_default_root(),
        help=(
            "Root folder to scan. Defaults to generated/batch_incident_runs if it exists; "
            "otherwise simulator/generated/batch_incident_runs."
        ),
    )
    parser.add_argument(
        "--min-area-km2",
        type=float,
        default=DEFAULT_MIN_AREA_KM2,
        help="Minimum area in square kilometers required for every incident/sub-incident region.",
    )
    parser.add_argument(
        "--tolerance-km2",
        type=float,
        default=DEFAULT_TOLERANCE_KM2,
        help="Numeric tolerance for approximate area calculations.",
    )
    parser.add_argument(
        "--incident-types",
        nargs="+",
        default=None,
        help=(
            "Optional incident-type filter. Accepts repeated values and/or comma-separated values, "
            "for example: --incident-types wildfire 'terrorist incident'. Matching is applied "
            "to run folders/run ids and sub-incident types; matching runs are kept whole."
        ),
    )
    parser.add_argument(
        "--legacy-multi-location-mode",
        choices=["composite", "separate"],
        default="composite",
        help=(
            "How to validate old GT files with multiple locations and no incident_region. "
            "composite treats them as one enclosing incident footprint; separate checks each tiny region."
        ),
    )
    parser.add_argument(
        "--json-output",
        type=Path,
        default=None,
        help="Optional path to write a detailed JSON validation report.",
    )
    parser.add_argument(
        "--csv-output",
        type=Path,
        default=None,
        help="Optional path to write one row per sub-incident.",
    )
    parser.add_argument(
        "--fail-on-invalid",
        action="store_true",
        help="Exit with status code 2 if any run/sub-incident fails validation.",
    )
    return parser.parse_args(argv)


def main(
    argv: Optional[Sequence[str]] = None,
    incident_types: Optional[Iterable[str]] = None,
    legacy_multi_location_mode: Optional[str] = None,
) -> int:
    """Validate generated incidents.

    ``incident_types`` is an optional programmatic filter. For example, call
    ``main(incident_types=["wildfire", "terrorist incident"])`` to focus on
    those incident families. CLI users can pass the same filter with
    ``--incident-types wildfire "terrorist incident"``. If both are provided,
    the explicit ``incident_types`` parameter takes precedence over CLI values.
    """
    args = parse_args(argv)
    root = args.root

    incident_types = ["wildfire", "fire", "terrorist incident", "civil protest"]

    selected_incident_types = split_incident_type_filters(
        incident_types if incident_types is not None else args.incident_types
    )
    selected_legacy_mode = legacy_multi_location_mode or args.legacy_multi_location_mode
    if selected_legacy_mode not in {"composite", "separate"}:
        print(
            f"ERROR: legacy_multi_location_mode must be 'composite' or 'separate', got {selected_legacy_mode!r}",
            file=sys.stderr,
        )
        return 1

    if not root.exists():
        print(f"ERROR: root folder does not exist: {root}", file=sys.stderr)
        return 1

    if selected_incident_types:
        print(f"Incident-type filter: {', '.join(selected_incident_types)}")

    runs = validate_root(
        root,
        args.min_area_km2,
        args.tolerance_km2,
        incident_types=selected_incident_types,
        legacy_multi_location_mode=selected_legacy_mode,
    )
    print_human_summary(runs, args.min_area_km2, args.tolerance_km2)

    if args.json_output is not None:
        write_json(
            args.json_output,
            runs,
            args.min_area_km2,
            args.tolerance_km2,
            selected_incident_types,
            selected_legacy_mode,
        )
        print(f"\nWrote JSON report: {args.json_output}")

    if args.csv_output is not None:
        write_csv(args.csv_output, runs)
        print(f"Wrote CSV report: {args.csv_output}")

    if args.fail_on_invalid and any(not r.all_subincidents_ok for r in runs):
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
